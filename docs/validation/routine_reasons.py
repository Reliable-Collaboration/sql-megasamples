"""Why each routine demo may execute is read-only, and the v1 inventory built from those reasons.

docs/validation/dl077-public-routines.py observes the facts and publishes; tests/test_v1_public_routines.py
regenerates every published row through publication(). PR #14's strict-read-inventory.py keeps its own
reasons as published with its 2026-11-18 evidence.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAMES = dict(re.findall(r"\('([^']+)','([^']+)'\)", (ROOT / 'engines/postgres/init/read-routine-names.sql').read_text()))
# Design 4.2's named exceptions, by exact signature: P-3's three built-ins and P-8's direct grant.
NAMED = {
    'pg_export_snapshot()': 'Publishes a snapshot that another session can import while the exporting transaction lives (design 4.2, P-3 and P-5)',
    'pg_current_snapshot()': 'Returns the current snapshot without assigning a transaction ID (design 4.2, P-3)',
    'pg_database_size(oid)': "Reads the database size using the caller's existing access (design 4.2, P-3)",
    'megasamples_policy_loaded()': "Reports whether the read_policy library was preloaded; a direct grant to demo, the healthcheck's account (design 4.2, P-8)",
}


def reason(routine, operators, casts):
    signature, namespace, name = routine['signature'], routine['namespace'], routine['name']
    if signature in NAMED:
        return NAMED[signature]
    if namespace == 'information_schema' and name.startswith('_pg_'):
        return 'Upstream information-schema helper: expands supplied arrays or reads type and index metadata'
    if signature in operators:
        return 'Implements an initdb operator: compares or computes supplied values without changing stored state'
    if signature in casts:
        return 'Implements an initdb cast: converts supplied values without changing stored state'
    if namespace == 'pg_catalog':
        return NAMES.get(name, 'NOT in explicit read policy')
    return 'NOT in explicit read policy'


FACTS = ("signature", "name", "namespace", "kind", "volatility")


def publication(observed, operators, casts, observed_at):
    """The v1 inventory's JSON object and Markdown from {database: [facts]}, or ValueError.

    Every database must give the same rows, no signature may repeat, and every routine needs a reason.
    """
    databases = list(observed)
    first = observed[databases[0]]
    for database, rows in observed.items():
        if rows != first:
            raise ValueError(f"{database}: demo's executable routines differ from {databases[0]}'s")
    signatures = [row["signature"] for row in first]
    repeated = sorted({s for s in signatures if signatures.count(s) > 1})
    if repeated:
        raise ValueError("listed more than once: " + ", ".join(repeated))
    routines = []
    for row in first:
        implements = [kind for kind, members in (("operator", operators), ("cast", casts)) if row["signature"] in members]
        routines.append({**{key: row[key] for key in FACTS}, "implements": implements,
                         "reason": reason(row, operators, casts)})
    missing = [r["signature"] for r in routines if "NOT in explicit" in r["reason"]]
    if missing:
        raise ValueError("routines without a reason: " + ", ".join(missing))
    inventory = {"observed_at": observed_at, "databases": databases, "count": len(routines), "routines": routines}
    lines = [f"Every routine `demo` can execute in the version 1 PostgreSQL candidate is listed below, with its reason. "
             f"The observed set is identical in all {len(databases)} inventoried databases. User-defined dataset "
             "routines are not executable by `demo`. One routine, `megasamples_policy_loaded()`, is granted to `demo` "
             "directly rather than to `PUBLIC` (design 4.2, P-8), so a new login does not hold the whole set.",
             "", f"Observed {observed_at}; {len(routines)} signatures, generated by "
             "`docs/validation/dl077-public-routines.py`. The [machine-readable inventory](dl-077-v1-public-routines.json) "
             "retains namespaces, routine kinds, volatility and the operator or cast each routine implements. "
             "Reasons concern stored-state effects, rather than the creation of ordinary query-result values. "
             "PR #14's 2026-11-18 inventory is retained separately as [its evidence](strict-read-executable-routines.md).",
             "", "| Routine | Why it is read-only |", "| --- | --- |"]
    lines += [f"| `{r['signature']}` | {r['reason']} |" for r in routines]
    return inventory, "\n".join(lines) + "\n"
